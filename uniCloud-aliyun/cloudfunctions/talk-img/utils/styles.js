/**
 * @function buildPrompt 装配最终提示词：主体描述在前(主导) + 画风基调在后(修饰) + 共用后缀
 * @param { String } styleId 风格卡 id
 * @param { String } userPrompt 用户输入的主体描述（性别/发色/发型/表情/姿势/服装/场景等全由此决定）
 * @returns { String }
 */
function buildPrompt (styleId, userPrompt, opts = {}) {
	const sp = STYLE_PROMPTS[styleId] || ''
	const u = (userPrompt || '').trim()
	const core = [u, sp].filter(Boolean).join('，')
	return `${core}${suffixFor(styleId, opts.i2i)}`
}

